"""Write the Gazebo world used at launch.

Runs before the Gazebo process starts, so the world can be regenerated from
``sentry_description/urdf/sentry_robot.urdf`` and :mod:`sentry_gazebo.arena_spec`
on every launch.  Also refreshes the mesh symlink so
``model://sentry_description/meshes/*.stl`` resolves through
``GZ_SIM_RESOURCE_PATH``.

Generated files (throw-away, never committed):

``rmul_2027.sdf``          the world (arena + robot + two ``gpu_lidar`` sensors)
``env.sh``                 the Gazebo environment of the launch file
``models/sentry_description/``  mesh shim (symlink to the URDF's ``meshes/``)
"""
import sys
from pathlib import Path

from sentry_gazebo import sdf_builder

# launch/ has no __init__.py (a module named "launch" would shadow ROS'
# python package), so the sibling helper is imported by file path.
sys.path.insert(0, str(Path(__file__).resolve().parent))
from launch_utils import generated_dir, urdf_path  # noqa: E402

WORLD = 'rmul_2027.sdf'


def generate(gen_root, urdf, view=False):
    """Write the world plus its mesh shim; return the world path.

    ``view=True`` adds the two PointCloud panels to the Gazebo GUI.
    """
    gen_root = Path(gen_root)
    urdf = Path(urdf)

    # mesh resource model: model://sentry_description/meshes/<stl>
    mesh_model = gen_root / 'models' / 'sentry_description'
    mesh_model.mkdir(parents=True, exist_ok=True)
    (mesh_model / 'model.config').write_text(
        '<?xml version="1.0"?>\n<model>\n  <name>sentry_description</name>\n'
        '  <version>1.0</version>\n'
        '  <description>mesh resource shim (generated)</description>\n</model>\n',
        encoding='utf-8')
    link = mesh_model / 'meshes'
    if link.is_symlink() or (link.exists() and link.is_file()):
        link.unlink()
    if not link.exists():
        link.symlink_to((urdf.parent.parent / 'meshes').resolve(), target_is_directory=True)

    world = gen_root / WORLD
    world.write_text(sdf_builder.build(str(urdf), view=view), encoding='utf-8')
    write_env_script(gen_root / 'env.sh')
    print('[sentry_gazebo] generated %s in %s (urdf %s)' % (WORLD, gen_root, urdf))
    return world


def write_env_script(path):
    """Shell snippet with the Gazebo environment of the launch file.

    Sourcing it lets ``gz sim -r -s <world>`` be run by hand with exactly the
    same resource paths as ``ros2 launch sentry_gazebo sim.launch.py``.
    """
    from launch_utils import gz_environment

    lines = ['# generated by sentry_gazebo prepare_world.py -- source me']
    for key, value in gz_environment().items():
        lines.append('export %s="%s"' % (key, value))
    Path(path).write_text('\n'.join(lines) + '\n', encoding='utf-8')
    return path


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    gen = Path(argv[0]) if argv else generated_dir()
    urdf = urdf_path()
    if not Path(urdf).is_file():
        print('[sentry_gazebo] URDF not found: %s' % urdf, file=sys.stderr)
        return 1
    generate(gen, urdf)
    return 0


if __name__ == '__main__':
    sys.exit(main())
